#!/usr/bin/env python3
"""Emit descriptors from ../descriptors.h as a standalone C header.

The emulator must present the byte-for-byte descriptors the harness tests
against, otherwise a hardware run proves nothing about the host results.
Generating them at build time rather than checking in a second copy is what
keeps the two from drifting apart.

    gen_desc.py <descriptors.h> <out.h> <c_name>=<prefix> [...]

Each pair yields `<prefix>_desc` and `<PREFIX>_DESC_LEN`. One header per
target, holding only that target's descriptors, so nothing lands in a binary
that does not use it.
"""
import re
import sys


def normalise_end_collection(data):
    """Rewrite End Collection items that carry a data byte.

    Every Gameball descriptor in the corpus encodes End Collection as 0xC1 0x00,
    which is bSize 1 where the HID spec says 0. Tolerant parsers skip it by size
    and never notice; a strict one reads the trailing 0x00 as an undefined Main
    item. This produces the well formed 0xC0 form so the two can be told apart on
    real hardware.
    """
    out, i, fixed = [], 0, 0
    while i < len(data):
        p = data[i]
        size = p & 3
        size = 4 if size == 3 else size
        if (p >> 2) & 3 == 0 and (p >> 4) & 0xF == 0xC and size:
            out.append(0xC0)
            fixed += 1
        else:
            out.extend(data[i:i + 1 + size])
        i += 1 + size
    return out, fixed


def fix_signed_axes(data):
    """Give relative axes a negative Logical Minimum.

    The Gameball descriptors never set Logical Minimum for X, Y, wheel or pan, so
    the 0 left over from the button block stands and the axes read as unsigned
    0..127. A parser that honours that discards every negative delta and the
    pointer can only travel right and down. deskhop reads the field as signed
    regardless and is unaffected; Windows is not.

    Inserts Logical Minimum -127 before the first relative Input item that needs
    it. It is a global item, so every axis after it inherits the fix.
    """
    out, i, fixed, lmin, lmax = [], 0, 0, None, None
    while i < len(data):
        p = data[i]
        size = p & 3
        size = 4 if size == 3 else size
        item = data[i:i + 1 + size]
        val = 0
        for k, d in enumerate(item[1:]):
            val |= d << (8 * k)
        typ, tag = (p >> 2) & 3, p & 0xFC

        if typ == 1 and tag == 0x14:
            lmin = val
        if typ == 1 and tag == 0x24:
            lmax = val
        if typ == 0 and tag == 0x80 and (val & 0x04) and lmin == 0 and lmax and not fixed:
            out.extend([0x15, (256 - lmax) & 0xFF])   # Logical Minimum -lmax
            lmin = -lmax
            fixed += 1

        out.extend(item)
        i += 1 + size
    return out, fixed


def extract(text, name):
    m = re.search(r'static const uint8_t %s\[\]\s*=\s*\{(.*?)\};' % re.escape(name),
                  text, re.S)
    if not m:
        sys.exit("gen_desc.py: %s not found" % name)

    body = re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S)
    body = re.sub(r'//[^\n]*', '', body)
    data = [int(b, 16) for b in re.findall(r'0[xX]([0-9A-Fa-f]{1,2})', body)]
    if not data:
        sys.exit("gen_desc.py: %s parsed to zero bytes" % name)
    return data


def main():
    flags = {"--normalise-end-collection", "--fix-signed-axes"}
    given = {a for a in sys.argv[1:] if a in flags}
    argv = [a for a in sys.argv[1:] if a not in flags]
    normalise = "--normalise-end-collection" in given
    signed = "--fix-signed-axes" in given
    src, out, pairs = argv[0], argv[1], argv[2:]
    if not pairs:
        sys.exit("gen_desc.py: no <c_name>=<prefix> pairs given")

    text = open(src).read()
    lines = ["/* Generated by emu/gen_desc.py from %s - do not edit. */" % src,
             "#pragma once",
             "#include <stdint.h>",
             ""]
    summary = []

    for pair in pairs:
        name, _, prefix = pair.partition("=")
        if not prefix:
            sys.exit("gen_desc.py: expected <c_name>=<prefix>, got %r" % pair)

        data = extract(text, name)
        if normalise:
            data, fixed = normalise_end_collection(data)
            if fixed:
                print("gen_desc.py: %s, rewrote %d End Collection item(s)" % (prefix, fixed))
        if signed:
            data, fixed = fix_signed_axes(data)
            if fixed:
                print("gen_desc.py: %s, gave the relative axes a signed range" % prefix)
        macro = prefix.upper() + "_DESC_LEN"

        lines.append("#define %s %d" % (macro, len(data)))
        lines.append("static const uint8_t %s_desc[%s] = {" % (prefix, macro))
        for i in range(0, len(data), 12):
            lines.append("    " + " ".join("0x%02X," % b for b in data[i:i + 12]))
        lines.append("};")
        lines.append("")
        summary.append("%s %d" % (prefix, len(data)))

    open(out, "w").write("\n".join(lines) + "\n")
    print("gen_desc.py: " + ", ".join(summary) + " bytes")


main()
