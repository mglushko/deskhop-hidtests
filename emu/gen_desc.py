#!/usr/bin/env python3
"""Emit descriptors from ../descriptors.h as a standalone C header.

The emulator must present the byte-for-byte descriptors the harness tests
against, otherwise a hardware run proves nothing about the host results.
Generating them at build time rather than checking in a second copy is what
keeps the two from drifting apart.

    gen_desc.py <descriptors.h> <out.h> <c_name>=<prefix> [...]

Each pair yields `<prefix>_desc` and `<PREFIX>_DESC_LEN`. One header per
target, holding only that target's descriptors, so nothing lands in a binary
that does not use it.
"""
import re
import sys


def extract(text, name):
    m = re.search(r'static const uint8_t %s\[\]\s*=\s*\{(.*?)\};' % re.escape(name),
                  text, re.S)
    if not m:
        sys.exit("gen_desc.py: %s not found" % name)

    body = re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S)
    body = re.sub(r'//[^\n]*', '', body)
    data = [int(b, 16) for b in re.findall(r'0[xX]([0-9A-Fa-f]{1,2})', body)]
    if not data:
        sys.exit("gen_desc.py: %s parsed to zero bytes" % name)
    return data


def main():
    src, out, pairs = sys.argv[1], sys.argv[2], sys.argv[3:]
    if not pairs:
        sys.exit("gen_desc.py: no <c_name>=<prefix> pairs given")

    text = open(src).read()
    lines = ["/* Generated by emu/gen_desc.py from %s - do not edit. */" % src,
             "#pragma once",
             "#include <stdint.h>",
             ""]
    summary = []

    for pair in pairs:
        name, _, prefix = pair.partition("=")
        if not prefix:
            sys.exit("gen_desc.py: expected <c_name>=<prefix>, got %r" % pair)

        data = extract(text, name)
        macro = prefix.upper() + "_DESC_LEN"

        lines.append("#define %s %d" % (macro, len(data)))
        lines.append("static const uint8_t %s_desc[%s] = {" % (prefix, macro))
        for i in range(0, len(data), 12):
            lines.append("    " + " ".join("0x%02X," % b for b in data[i:i + 12]))
        lines.append("};")
        lines.append("")
        summary.append("%s %d" % (prefix, len(data)))

    open(out, "w").write("\n".join(lines) + "\n")
    print("gen_desc.py: " + ", ".join(summary) + " bytes")


main()
