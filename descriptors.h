/*==============================================================================
 *  Registry
 *============================================================================*/

typedef struct {
    const char    *name;
    const uint8_t *bytes;
    int            len;
} descriptor_t;

#define D(x) {#x, d_##x, (int)sizeof(d_##x)}

static const descriptor_t descriptors[] = {
    D(gameball_trackball),
    D(gameball_gesture),
    D(gameball_keyboard),
    D(boot_mouse),
    D(hires_mouse),
    D(boot_keyboard),
    D(nkro_keyboard),
    D(consumer),
    D(system),
    D(composite),
    D(many_usages),
    D(vendor_then_mouse),
};

#undef D

static inline const descriptor_t *find_descriptor(const char *name) {
    for (unsigned i = 0; i < sizeof(descriptors) / sizeof(descriptors[0]); i++)
        if (strcmp(descriptors[i].name, name) == 0)
            return &descriptors[i];
    return NULL;
}
