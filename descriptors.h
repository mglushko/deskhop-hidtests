/* Corpus of HID report descriptors.
 *
 * Add one entry per device that shows up in an issue, with the issue number in
 * the comment. Real captured bytes are kept verbatim, including quirks like the
 * 0xC1 0x00 form of End Collection, because reproducing the quirk is the point.
 *
 * Synthetic entries are marked as such and exist to probe specific parser
 * behaviour rather than to represent a real device.
 */
#pragma once

#include <stdint.h>

/* Every binary that includes this file uses a handful of these and ignores the
   rest - mousetest reaches for nine, kbdtest for twelve, dump for the registry.
   That is the intended use, not an oversight, so the warning is turned off here
   and only here. It used to be turned off for the whole build with
   -Wno-unused-variable in CFLAGS, which also hid genuinely unused locals in the
   test code itself. */
#pragma GCC diagnostic push
#pragma GCC diagnostic ignored "-Wunused-variable"
#pragma GCC diagnostic ignored "-Wunused-const-variable"

/*==============================================================================
 *  Gameball trackball, VID 0782 PID 001B - github.com/hrvach/deskhop/issues/332
 *
 *  All three of these encode End Collection as 0xC1 0x00, which is bSize 1 where
 *  the HID spec says 0 - every End Collection item in the three, five in total.
 *  deskhop's parser skips the item by its declared size and is unaffected, which
 *  `make dump` and `make mouse` both confirm: every field lands at the right
 *  offset either way.
 *
 *  Windows is not so relaxed. Emulating the trackball interface on an RP2040 and
 *  plugging it into a PC, the bytes below enumerate and are then suspended with
 *  no driver bound, and rewriting only those items to 0xC0 makes the same device
 *  work. Nothing else changed between the two builds.
 *
 *  These bytes are therefore not what the device sends, and the dump says so
 *  itself. Its device paths read
 *
 *      \\?\hid#vid_0782&pid_001b&mi_01&col02#...{4d1e55b2-f16f-11cf-88cb-...}
 *
 *  which is GUID_DEVINTERFACE_HID, so it was taken on Windows, and the col01 and
 *  col02 suffixes are Windows splitting one interface into a device per
 *  collection. That view only exists in the parsed caps, not on the wire. So the
 *  tool was reading Windows' parsed structure and rebuilding a descriptor from
 *  it, which is exactly the failure mode already recorded further down this file
 *  for winhiddump's HidSharp backend: reconstruction from caps, wrong in ways
 *  that matter. Rebuilding End Collection with a size byte, and losing a Logical
 *  Minimum that was inherited from an earlier global, are both what that produces.
 *
 *  They are left as dumped, because the corpus records what was reported and no
 *  result here depends on it, but anything drawing conclusions from these exact
 *  bytes should know. emu/ builds gameball-c0-emu and gameball-fixed-emu to keep
 *  the comparison live.
 *
 *  A second anomaly says the same thing more strongly. The trackball's X, Y,
 *  wheel and pan carry no Logical Minimum of their own, so the 0 left over from
 *  the button block stands and all four read as unsigned 0..127. A trackball that
 *  really declared that could only ever travel right and down, and emulating these
 *  bytes reproduces exactly that on a PC: the pointer walks down and right in steps
 *  and no negative movement survives. Every other relative axis in this corpus
 *  declares a negative Logical Minimum: 0x15 0x81 on d_pixart_mouse, 0x16 0x01 0xF8
 *  on d_mx518_mouse, 0x16 0x00 0xF8 on d_kernel_multi_collection.
 *
 *  deskhop is unaffected by both. get_report_value reads the field as signed from
 *  its size rather than from the declared range, which `make mouse` confirms:
 *  0xEC decodes to -20. So the harness numbers stand either way, and the two
 *  anomalies are evidence about the dump rather than about the parser. Together
 *  they suggest #332's descriptor was reconstructed from parsed data rather than
 *  captured, since a reconstruction is exactly what loses a global item that was
 *  inherited and re-encodes End Collection with a size byte.
 *============================================================================*/

